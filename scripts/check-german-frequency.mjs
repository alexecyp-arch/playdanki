import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {selectGermanWords,germanFrequencyAudit} from './select-german-words.mjs';
import {canonical,rankGermanWords} from './german-frequency-rules.mjs';
const read=async path=>JSON.parse(await fs.readFile(path,'utf8'));
const source=await read('src/words.json'),cards=await read('dist/german/words.json'),snapshot=await read('scripts/german-frequency-snapshot.json');
assert.equal(source.length,5000,'Archived source stays intact');
assert.equal(cards.length,1200);
assert.deepEqual(cards,selectGermanWords(source));
const key=word=>canonical(word).toLocaleLowerCase('de-DE');
assert.equal(new Set(cards.map(c=>key(c[0]))).size,1200);
assert(cards.every(c=>c.length===4&&c[0].trim()&&c[1].trim()&&Array.isArray(c[3])));
const expected=rankGermanWords(snapshot).slice(0,1199).map(r=>key(r.word));expected.push('sich');
assert.deepEqual(cards.map(c=>key(c[0])).sort(),expected.sort());
const forbidden=['frank','michael','charlie','david','alex','richard','bob','sarah','nina','pascal','sabine','i','wa','triefen','typus'];
assert(cards.every(c=>!forbidden.includes(c[0].toLowerCase())),'No reviewed names or annotation mistakes');
assert(!cards.some(c=>c[0]==='Rosa'));assert.equal(cards.find(c=>c[0]==='rosa')?.[1],'pink');
const audit=await read('dist/german/frequency-audit.json');assert.deepEqual(audit,germanFrequencyAudit(source));
assert(audit.records.every(r=>r.subtitleCount>0&&r.subtitleWordFormRank>=1&&r.subtitleWordFormRank<=10000));
assert.equal(audit.records.filter(r=>r.privateConversationCount>0).length,1199);
const translations=new Map(cards.map(c=>[key(c[0]),c[1]]));
for(const [word,meaning]of [['frage','question'],['ei','egg'],['rücken','back (body part)'],['regen','rain (noun)'],['rum','around (informal)']])assert.equal(translations.get(word),meaning);
const home=await fs.readFile('dist/index.html','utf8'),core=JSON.parse(home.match(/id="core-deck-info"[^>]*>([\s\S]*?)<\/script>/)[1]);
assert.equal(core['german-word'].count,1200);
const seed=JSON.parse(home.match(/id="word-data"[^>]*>([\s\S]*?)<\/script>/)[1]);assert.deepEqual(seed,cards.slice(0,32));
console.log('German frequency audit passed: 1200 unique reviewed cards, 1200 subtitle attestations, 1199 private-conversation attestations, explicit reflexive exception, names removed, meanings and lazy metadata checked.');
