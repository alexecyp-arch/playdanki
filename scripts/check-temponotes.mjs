import assert from 'node:assert/strict';
import {createNotesStore} from '../src/temponotes/notes-store.mjs';
let clock=1800000000000,watchers=new Map(),queue=Promise.resolve(),rows=new Map();
const auth={currentUser:{uid:'alice'}};
const snapshot=r=>({exists:()=>rows.has(r),data:()=>rows.get(r)});
const emit=()=>{for(const [prefix,callback]of watchers)callback({docs:[...rows].filter(([r])=>r.startsWith(prefix+'/')).map(([r,value])=>({id:r.split('/').at(-1),data:()=>value}))});};
const sdk={doc:(_, ...p)=>p.join('/'),collection:(_, ...p)=>p.join('/'),serverTimestamp:()=>({toMillis:()=>clock}),setDoc:async(r,v)=>rows.set(r,v),getDoc:async r=>snapshot(r),deleteDoc:async r=>{rows.delete(r);emit();},onSnapshot:(prefix,callback)=>{watchers.set(prefix,callback);emit();return()=>watchers.delete(prefix);},runTransaction:(_,fn)=>{const task=queue.then(async()=>{const writes=[];const value=await fn({get:async r=>snapshot(r),set:(r,v)=>writes.push(()=>rows.set(r,v)),update:(r,v)=>writes.push(()=>rows.set(r,{...rows.get(r),...v})),delete:r=>writes.push(()=>rows.delete(r))});writes.forEach(f=>f());emit();return value;});queue=task.catch(()=>{});return task;}};
const store=await createNotesStore({auth,db:{},sdk,uid:'alice',now:()=>clock});
const id='00000000-0000-4000-a000-000000000001';
const call=(method,data)=>store.request('/api/notes',{method,body:JSON.stringify(data)});
assert.equal((await call('POST',{id,body:'  private note  ',minutes:60})).status,200);
assert.equal((await call('POST',{id,body:'retry',minutes:60})).status,200);
let list=(await (await store.request('/api/notes')).json()).notes;
assert.equal(list.length,1);assert.equal(list[0].body,'private note');assert.equal(list[0].expiresAt-clock,3600000);
await Promise.all([call('PATCH',{id,minutes:30}),call('PATCH',{id,minutes:60})]);
list=(await (await store.request('/api/notes')).json()).notes;
assert.equal(list[0].expiresAt-clock,9000000,'concurrent extensions must both apply');
assert.equal((await call('PATCH',{id,minutes:5})).status,400);
assert.equal((await call('POST',{id:'bad',body:'hello',minutes:60})).status,400);
assert.equal((await call('POST',{id,body:'x'.repeat(10001),minutes:60})).status,400);
clock+=9000001;
assert.equal((await call('PATCH',{id,minutes:30})).status,400,'expired notes cannot be revived');
assert.deepEqual((await (await store.request('/api/notes')).json()).notes,[]);
await queue;assert.equal(rows.has('users/alice/temponotes/'+id),false,'expired storage cleanup');
const eternalId='00000000-0000-4000-a000-000000000002';
const schedule=(method,data)=>store.request('/api/eternal',{method,body:JSON.stringify(data)});
assert.equal((await schedule('POST',{id:eternalId,body:'150 PUSHUPS',days:[3]})).status,200);
assert.equal((await schedule('POST',{id:eternalId,body:'retry',days:[3]})).status,200);
let schedules=(await (await store.request('/api/notes')).json()).eternalNotes;
assert.equal(schedules.length,1);assert.equal(schedules[0].body,'150 PUSHUPS');
assert.equal((await schedule('PATCH',{id:eternalId,body:'160 PUSHUPS',days:[1,3,5]})).status,200);
assert.equal((await schedule('PATCH',{id:eternalId,dismiss:true})).status,200);
schedules=(await (await store.request('/api/notes')).json()).eternalNotes;
assert.equal(schedules[0].body,'160 PUSHUPS');assert(schedules[0].dismissedOn);assert.deepEqual(schedules[0].days,[1,3,5]);
assert.equal((await schedule('POST',{id:eternalId,body:'bad',days:[]})).status,400);
assert.equal((await schedule('POST',{id:eternalId,body:'bad',days:[8]})).status,400);
assert.equal((await schedule('POST',{id:eternalId,body:'bad',days:[3,3]})).status,400);
assert.equal((await store.request('/api/eternal?id='+eternalId,{method:'DELETE'})).status,200);
assert.equal((await (await store.request('/api/notes')).json()).eternalNotes.length,0);
auth.currentUser={uid:'bob'};
assert.equal((await schedule('POST',{id:eternalId,body:'wrong account',days:[3]})).status,400);
assert.equal((await call('POST',{id,body:'wrong account',minutes:60})).status,400);
assert.equal(rows.has('users/bob/temponotes/'+id),false);
store.dispose();assert.equal((await store.request('/api/notes')).status,400);
console.log('Temponote checks passed: retry, expiry, atomic extensions, validation, account changes and cleanup.');
